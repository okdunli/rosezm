/**
 * rosezm - the iOS shell's manual verification checklist.
 *
 * The framework cannot run an iOS build on this machine (no Xcode, no
 * signing identity, no device) - and an export that pretended otherwise
 * would be lying. What it CAN do honestly is attach, to every iOS-capable
 * export, the exact checklist a human with Xcode + a device must walk
 * before trusting the shell: install, launch, splash handshake, back
 * button, deep link, offline start, the capability bridge.
 *
 * The checklist is generated from the project's REAL declarations (its
 * splash config, its scheme, its useNative capabilities, its offline
 * policy), so it names what THIS app should show - not a generic leaflet.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import type { AppIdentity } from './app-identity.js';

export const IOS_VERIFY_FILE = 'IOS-VERIFY.md';

export interface IosVerifyFacts {
  app: AppIdentity;
  /** The capabilities the project declared through useNative. */
  capabilities: readonly string[];
  /** Whether the export carried the web build (the --webview mode). */
  webview?: boolean;
}

export function renderIosVerify(f: IosVerifyFacts): string {
  const app = f.app;
  const caps = f.capabilities.length ? f.capabilities.map((c) => `- \`${c}\``).join('\n') : '- (no useNative capabilities declared)';
  const splash = app.splash
    ? `- Splash: ${app.splash.backgroundColor ?? '(no colour)'}${app.splash.image ? ' + image' : ''} — the splash must stay up until the page paints (rosezm-splash.js handshake), then fade`
    : '- Splash: none declared — the WebView paints directly (watch for a white flash on cold start)';
  const scheme = app.scheme
    ? `- Deep link: open \`${app.scheme}:///\` from Safari — the app must open on the start route`
    : '- Deep link: no scheme declared — skip this step';
  const offline = app.offline?.serviceWorker
    ? '- Offline start: enable airplane mode, relaunch — a baked route must paint its first frame from the Service Worker cache'
    : '- Offline start: no Service Worker declared — airplane mode will show the platform error page';
  const progress = app.showLoadProgress
    ? '- Load bar: the 2px top bar must advance through its milestones and fade on the first frame'
    : '- Load bar: not enabled — skip this step';
  return `# iOS shell — manual verification checklist

> Generated by \`rosezm export\`. This machine did not run an iOS build
> (no Xcode / signing identity / device attached is a hard gate the
> framework will not fake). Walk this list on a real device before
> trusting the shell; every step names what THIS app should do.

- App: **${app.name}** (\`${app.id}\`), version ${app.version}, build ${app.version.split('.').join('')}

## Build & install

1. \`open ${app.slug}/xcworkspace\` (or the xcodeproj) in Xcode; select the
   app target and your signing team.
2. Run on a physical device (a simulator skips the gestures this checklist
   covers).

## Launch

3. Cold start: ${splash}
4. First content: the start route's document must paint with no white
   flash between the splash and the first frame.
${progress}

## Interaction

5. Back: from a sub-route, the edge-swipe from the left screen edge (and
   the hardware/toolbar back, where present) must navigate back — or close
   an app-level dialog if the app handles \`rosezm:back\`.
${scheme}
6. Capabilities declared by this app:
${caps}
   Each must answer through the shell bridge — a capability that returns
   null on iOS when the desktop shell answers it is a gap to report.
${offline}
7. External links: a \`target="_blank"\` link follows the app's
   \`externalLinks\` policy (\`${app.externalLinks ?? 'system'}\`).

## Report

A step that fails is a bug to record with the device model, iOS version,
and the step number. Do not ship a build that skipped a step.
`;
}

/** Attach the checklist to an iOS-capable export's root. Returns the file
 *  name, or null when the caller chose not to ship one. */
export async function writeIosVerify(exportRoot: string, facts: IosVerifyFacts): Promise<string | null> {
  await fs.promises.mkdir(exportRoot, { recursive: true });
  await fs.promises.writeFile(path.join(exportRoot, IOS_VERIFY_FILE), renderIosVerify(facts), 'utf8');
  return IOS_VERIFY_FILE;
}
