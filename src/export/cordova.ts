/**
 * rosezm - the Cordova shell.
 *
 * Capacitor's elder sibling: the same idea (the built site inside a native
 * WebView project a store accepts), the older toolchain. Cordova earns a target
 * because a large installed base of apps still ships through it - and a rosezm
 * export is the best possible input for it: one self-contained document per
 * route, no router to boot, no hydration to pay for.
 *
 * Output:
 *   cordova/config.xml     - widget id, name, version, content src=index.html
 *   cordova/package.json   - the cordova CLI and its two platforms
 *   cordova/www/           - the built site (prerendered documents + assets)
 *   cordova/DEPLOY.md      - cordova platform add / run / build
 *   cordova/.gitignore     - the native projects cordova generates
 *
 * Honest boundary: `platforms/` and `plugins/` are generated by `cordova
 * platform add` on a machine with the platform SDK - the export ships the web
 * half and the config, because the native half is Cordova's.
 */
