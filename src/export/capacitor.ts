/**
 * rosezm - the Capacitor shell (0.2.0).
 *
 * The third way to reach an app store, next to the native targets (Compose,
 * SwiftUI, ArkTS - source that compiles to real widgets) and the desktop shells
 * (Electron, Tauri, Wails - a window over the built site): Capacitor puts the
 * SAME built site into a native WebView project a store accepts.
 *
 * Why it earns a target: a rosezm app is already one inlined document with zero
 * hydration, which is the best possible input for a WebView - no SPA router to
 * boot, no data fetch on launch. Capacitor then adds what a WebView alone does
 * not have: the native container, the store metadata, plugin access (camera,
 * filesystem, push) through the same JS the app already runs.
 *
 * Output:
 *   capacitor/capacitor.config.json  - appId, appName, webDir: www
 *   capacitor/package.json           - @capacitor/core cli android ios
 *   capacitor/www/                   - the built site (from source, like electron)
 *   capacitor/DEPLOY.md              - cap add / cap sync / open
 *   capacitor/.gitignore             - the native projects cap generates
 *
 * Honest boundary: `android/` and `ios/` are generated by `npx cap add` on a
 * machine with the platform SDK - the export ships the web half and the config,
 * because the native half is Capacitor's, not the framework's.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { scanComponentFiles } from '../compiler/index.js';
import { appIdentity } from './app-identity.js';

export interface EmitCapacitorOptions {
  projectRoot: string;
  outDir: string;
  apiBase?: string;
  warnings: string[];
}

async function copyTree(from: string, to: string): Promise<void> {
  await fs.promises.mkdir(to, { recursive: true });
  for (const entry of await fs.promises.readdir(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) await copyTree(src, dest);
    else await fs.promises.copyFile(src, dest);
  }
}

/** Route paths from a built tree: every index.html is a route, the same mapping
 *  the server uses (`dist/blog/1/index.html` -> `/blog/1`). */
async function walkIndex(dir: string, prefix = ''): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await fs.promises.readdir(dir, { withFileTypes: true })) {
    const next = prefix + '/' + entry.name;
    if (entry.isDirectory()) out.push(...(await walkIndex(path.join(dir, entry.name), next)));
    else if (entry.name === 'index.html') out.push(next.slice(0, -'/index.html'.length) || '/');
  }
  return out;
}

export async function emitCapacitor(opts: EmitCapacitorOptions): Promise<{ pages: string[]; components: string[] }> {
  const out = path.join(opts.outDir, 'capacitor');
  const app = appIdentity(opts.projectRoot);
  let pages: string[] = [];
  let components: string[] = [];
  await fs.promises.rm(out, { recursive: true, force: true });
  await fs.promises.mkdir(out, { recursive: true });

  // A WebView has no server: unlike the Electron shell (which carries the prod
  // server), Capacitor can only show files that already exist. So this target
  // ships the PRERENDERED site - `rosezm build`'s output - and says so loudly
  // when there is none, instead of writing an empty www/ that boots to nothing.
  const site = path.join(out, 'www');
  const dist = path.join(opts.projectRoot, 'dist');
  if (fs.existsSync(path.join(dist, 'index.html'))) {
    await copyTree(dist, site);
    pages = (await walkIndex(dist)).sort();
    components = (await scanComponentFiles(opts.projectRoot)).map((f) => path.basename(f, '.rose'));
  } else {
    await fs.promises.mkdir(site, { recursive: true });
    opts.warnings.push('capacitor: the project has no built dist/ - run `rosezm build` (or export with --build) so the WebView has documents to show');
    components = (await scanComponentFiles(opts.projectRoot)).map((f) => path.basename(f, '.rose'));
  }

  const config = {
    appId: app.id,
    appName: app.name,
    webDir: 'www',
    // A rosezm document is one self-contained file: the WebView loads it from
    // the bundle, so there is no dev server URL and no remote host to whitelist.
    bundledWebRuntime: false,
    server: {
      // https by default on Android, which is what a store build expects and
      // what a Service Worker needs on iOS.
      androidScheme: 'https',
    },
  };
  await fs.promises.writeFile(path.join(out, 'capacitor.config.json'), JSON.stringify(config, null, 2) + '\n', 'utf8');

  const pkg = {
    name: app.slug,
    version: app.version,
    private: true,
    description: `${app.name} - a rosezm app, exported with rosezm export capacitor`,
    scripts: {
      sync: 'cap sync',
      'add:android': 'cap add android',
      'add:ios': 'cap add ios',
      'open:android': 'cap open android',
      'open:ios': 'cap open ios',
    },
    dependencies: { '@capacitor/core': '^6.1.0' },
    devDependencies: {
      '@capacitor/cli': '^6.1.0',
      '@capacitor/android': '^6.1.0',
      '@capacitor/ios': '^6.1.0',
    },
  };
  await fs.promises.writeFile(path.join(out, 'package.json'), JSON.stringify(pkg, null, 2) + '\n', 'utf8');

  // The native projects are regenerated by `cap add`, so they are not tracked;
  // www/ IS tracked because this export wrote it.
  await fs.promises.writeFile(path.join(out, '.gitignore'), ['node_modules/', 'android/', 'ios/', ''].join('\n'), 'utf8');

  const apiLine = opts.apiBase
    ? `The app talks to \`${opts.apiBase}\` for \`$data\` and server actions (baked into the build).`
    : 'No `--api` was given, so the app runs on the state the build baked in - an offline-capable shell.';
  await fs.promises.writeFile(path.join(out, 'DEPLOY.md'), `# ${app.name} - Capacitor

A store-ready wrapper around the built rosezm site. ${apiLine}

## One-time setup

\`\`\`bash
npm install
npx cap add android   # needs the Android SDK; generates android/
npx cap add ios       # needs Xcode; generates ios/
\`\`\`

## The edit loop

\`\`\`bash
# from the project root, whenever the .rose sources change:
rosezm export capacitor . --out build --build
cd build/capacitor && npx cap sync
\`\`\`

\`cap sync\` copies \`www/\` into the native projects and updates the plugin
bridges. Then run it the way that platform always runs:

\`\`\`bash
npx cap run android        # or: open build/capacitor/android in Android Studio
npx cap run ios            # or: open build/capacitor/ios in Xcode
\`\`\`

## Store builds

\`\`\`bash
cd android && ./gradlew bundleRelease      # .aab for Google Play
cd ios && xcodebuild -workspace App.xcworkspace -scheme App -configuration Release archive
\`\`\`

Signing is the platform's own: a keystore for Android, a provisioning profile
for iOS. Nothing in this export signs for you.

## Why the site is a directory of files

rosezm serves one self-contained document per route, so \`www/index.html\` is a
complete app on its own; the other files are the static routes and assets it
links to. There is no client-side router to warm up and no hydration pass: the
WebView paints the document the build wrote.
`, 'utf8');

  return { pages, components };
}
