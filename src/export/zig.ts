/**
 * rosezm - the Zig export (0.2.0).
 *
 * One `.rose` tree already leaves the web as fourteen apps; this target is the
 * fifteenth and the only one that is not a UI. It answers the other half of
 * "full stack": the built site as a SINGLE static binary you cross-compile for
 * whatever the server runs, from this machine, with no toolchain per platform.
 * That is Zig's one genuinely unmatched feature - `-Dtarget=x86_64-linux-musl`
 * produces a static Linux binary from Windows, in one command - and it is why
 * this target exists rather than another Node image.
 *
 * What it is honest about: a static server cannot run `dist/server.js`, so the
 * dynamic half (unbaked routes, server actions, `$data`) is not here. Every
 * route is baked at export time, and what a page still needs at runtime rides
 * the bridge to `--api`. The Node and Go servers remain the answer when the app
 * has a live backend.
 *
 * Output:
 *   zig/build.zig          - one exe, `-Dtarget`/`-Doptimize` pass through
 *   zig/main.zig           - HTTP/1.1 over std.net, ETag + 304, route fallback
 *   zig/assets.zig         - generated: every frontend file as @embedFile
 *   zig/frontend/          - the baked site (one document per route)
 *   zig/README.md
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { scanRoseFiles, scanComponentFiles } from '../compiler/index.js';
import { nativeUsage } from './native-api.js';
import { keepOnlyExcept } from './fs-util.js';
import { bakeShellDocuments, pageNames, pruneServerBundle, stageBuiltSite, shellCapabilityGaps, writeShellBridge } from './desktop-shell.js';
import { appBuildNumber, appIdentity, type AppIdentity } from './app-identity.js';
import { writeDeployScaffold } from './deploy-scaffold.js';

const LABEL = 'zig';

export interface EmitZigOptions {
  projectRoot: string;
  outDir: string;
  apiBase?: string;
  warnings: string[];
}

export async function emitZig(opts: EmitZigOptions): Promise<{ pages: string[]; components: string[] }> {
  const out = path.join(opts.outDir, LABEL);
  await keepOnlyExcept(out, ['zig-out', '.zig-cache']);
  await fs.promises.mkdir(out, { recursive: true });

  // The store identity, from the project's rosezm.app.json (defaults otherwise).
  const app = appIdentity(opts.projectRoot);
  const pageFiles = await scanRoseFiles(opts.projectRoot);
  const compFiles = await scanComponentFiles(opts.projectRoot);
  const native = nativeUsage(await Promise.all([...pageFiles, ...compFiles].map((f) => fs.promises.readFile(f, 'utf8'))));

  const frontend = path.join(out, 'frontend');
  await stageBuiltSite(opts.projectRoot, frontend, LABEL, opts.warnings);
  const docs = await bakeShellDocuments(pageFiles, frontend, LABEL, opts.warnings);
  // The binary embeds bytes; `server.js` is the SSR bundle it cannot run, and
  // inside a shipped artifact it is also every API route and its credentials.
  await pruneServerBundle(frontend);
  await writeShellBridge(frontend, opts.apiBase ?? '', native, { id: app.id, name: app.name, version: app.version, build: appBuildNumber(app.version) });
  for (const gap of shellCapabilityGaps(native)) opts.warnings.push(`${LABEL}: useNative('${gap}') has no shell equivalent - the bridge answers the contract's null at runtime`);

  const files = walkFiles(frontend);
  await fs.promises.writeFile(path.join(out, 'assets.zig'), renderAssets(files), 'utf8');
  await fs.promises.writeFile(path.join(out, 'main.zig'), renderMain(), 'utf8');
  await fs.promises.writeFile(path.join(out, 'main_io.zig'), renderMainIo(), 'utf8');
  await fs.promises.writeFile(path.join(out, 'build.zig'), renderBuild(app), 'utf8');
  await fs.promises.writeFile(path.join(out, 'build.zig.zon'), renderZon(app), 'utf8');
  await fs.promises.writeFile(path.join(out, 'README.md'), renderReadme(opts.apiBase ?? '', files.length, docs, app), 'utf8');
  await writeDeployScaffold('zig', out, opts.warnings);

  return {
    pages: pageNames(pageFiles),
    components: compFiles.map((f) => path.basename(f, '.rose')),
  };
}

/** Every emitted file, relative to the frontend root, posix separators. */
function walkFiles(dir: string, base = dir): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkFiles(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/**
 * `@embedFile` needs a literal path, so the list is generated. Zig resolves the
 * path relative to the file that embeds it, which is why every entry walks up
 * out of `src/`.
 */
function renderAssets(files: string[]): string {
  const rows = files.map((f) => `    .{ .path = ${JSON.stringify(f)}, .bytes = @embedFile("frontend/${f}") },`).join('\n');
  return `// Generated by \`rosezm export zig\` - do not edit. One entry per file the
// server can answer, embedded into the binary at compile time.
pub const Entry = struct { path: []const u8, bytes: []const u8 };

pub const all = [_]Entry{
${rows}
};
`;
}

/**
 * The version boundary, stated where the toolchain reads it: 0.15 is where
 * `addExecutable` takes a module (`root_module`), which is the shape build.zig
 * is written against - an older Zig refuses this tree with one sentence instead
 * of a hundred type errors.
 */
function renderZon(app: AppIdentity): string {
  return `.{
    .name = .rosezm_zig,
    .version = "${app.version}",
    .minimum_zig_version = "0.15.0",
    .fingerprint = 0xf47cdab58804df3,
    .dependencies = .{},
    .paths = .{ "build.zig", "build.zig.zon", "main.zig", "main_io.zig", "assets.zig", "frontend", "README.md" },
}
`;
}

function renderBuild(app: AppIdentity): string {
  return `const std = @import("std");

// One executable, no dependencies. The cross-compilation story is the whole
// point of this target: from any host,
//   zig build -Doptimize=ReleaseSmall -Dtarget=x86_64-linux-musl
// writes a static Linux binary into zig-out/bin.
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    // Zig 0.17 removed std.net, so the same server is written twice and the
    // toolchain picks the file its own std can compile: main.zig speaks
    // std.net (0.15, 0.16), main_io.zig speaks std.Io (0.17+).
    const source = if (@hasDecl(std, "net")) "main.zig" else "main_io.zig";
    const exe = b.addExecutable(.{
        .name = "${app.slug}",
        .root_module = b.createModule(.{
            .root_source_file = b.path(source),
            .target = target,
            .optimize = optimize,
        }),
    });
    b.installArtifact(exe);

    const run = b.addRunArtifact(exe);
    run.step.dependOn(b.getInstallStep());
    b.step("run", "Run the server").dependOn(&run.step);
}
`;
}

